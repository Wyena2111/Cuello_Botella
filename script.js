    // ================= 6C. MAPA DE CALOR: HORAS PICO DE VISITAS POR DÍA =================
    // Responde a AMBOS filtros (Centro y Descripción del Área).
    // Escala de color: azul (bajo) -> amarillo (intermedio) -> rojo (crítico),
    // relativa al valor máximo de la selección actual.
    const HM_DAYS = [0, 1, 2, 3, 4, 5]; // Lunes a Sábado (Domingo no tiene visitas en el CSV)
    const HM_STOPS = [
        { t: 0.00, c: [90, 160, 214] },   // azul
        { t: 0.35, c: [255, 242, 161] },  // amarillo
        { t: 0.70, c: [242, 107, 58] },   // naranja-rojo
        { t: 1.00, c: [165, 15, 45] }     // rojo intenso
    ];

    function heatColor(t) {
        const x = Math.max(0, Math.min(1, t));
        for (let i = 1; i < HM_STOPS.length; i++) {
            if (x <= HM_STOPS[i].t) {
                const a = HM_STOPS[i - 1], b = HM_STOPS[i];
                const k = (x - a.t) / (b.t - a.t);
                return a.c.map((v, j) => Math.round(v + (b.c[j] - v) * k));
            }
        }
        return HM_STOPS[HM_STOPS.length - 1].c;
    }

    function rgbCss(c) { return `rgb(${c[0]}, ${c[1]}, ${c[2]})`; }

    function heatTextColor(c) {
        const lum = (0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]) / 255;
        return lum > 0.6 ? '#1E293B' : '#FFFFFF';
    }

    // 13749 -> "13.749k" | 2662 -> "2662"
    function formatHeatCell(v) {
        if (v >= 10000) return `${Number((v / 1000).toFixed(3))}k`;
        return String(v);
    }

    function formatHourLong(h) {
        const suffix = h < 12 ? 'a. m.' : 'p. m.';
        const h12 = h % 12 === 0 ? 12 : h % 12;
        return `${h12}:00 ${suffix}`;
    }

