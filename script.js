    function calculateMedian(values) {
        if (!values.length) return null;
        const sorted = [...values].sort((a, b) => a - b);
        const mid = Math.floor(sorted.length / 2);
        return sorted.length % 2 !== 0
            ? sorted[mid]
            : (sorted[mid - 1] + sorted[mid]) / 2;
    }

    function computeFilteredMetrics(selectedCentro, selectedArea) {
        const isUnfiltered = selectedCentro === 'ALL' && selectedArea === 'ALL';

        const filteredRows = DATA_RECORDS.filter(rec => {
            const matchCentro = selectedCentro === 'ALL' || rec.centro === selectedCentro;
            const matchArea = selectedArea === 'ALL' || rec.DescripcionArea === selectedArea;
            return matchCentro && matchArea;
        });

        let totalVisitas = 0;
        let totalAtendidas = 0;
        let totalNoAtendidas = 0;

        const validMedianas = [];
        const validP90 = [];
        const validQ1 = [];

        filteredRows.forEach(rec => {
            totalVisitas += rec.TotalVisitas;
            totalAtendidas += rec.TotalAtendidas;
            totalNoAtendidas += rec.TotalNoAtendidas;

            if (rec.TiempoEspera_Mediana !== null) validMedianas.push(rec.TiempoEspera_Mediana);
            if (rec.TiempoEspera_P90 !== null) validP90.push(rec.TiempoEspera_P90);
            if (rec.TiempoEspera_Q1 !== null) validQ1.push(rec.TiempoEspera_Q1);
        });

        const pctAtendidas = totalVisitas > 0 ? (totalAtendidas / totalVisitas) * 100 : 0;
        const pctNoAtendidas = totalVisitas > 0 ? (totalNoAtendidas / totalVisitas) * 100 : 0;

        const esperaMediana = filteredRows.length === 1
            ? filteredRows[0].TiempoEspera_Mediana
            : calculateMedian(validMedianas);

        // Cuando no hay ningún filtro activo, Máximo (P90) y Mínimo (Q1) quedan en null para mostrar "-- --"
        let esperaMaximoP90 = null;
        let esperaMinimoQ1 = null;

        if (!isUnfiltered) {
            esperaMaximoP90 = filteredRows.length === 1
                ? filteredRows[0].TiempoEspera_P90
                : calculateMedian(validP90);

            esperaMinimoQ1 = filteredRows.length === 1
                ? filteredRows[0].TiempoEspera_Q1
                : calculateMedian(validQ1);
        }

        return {
            isUnfiltered,
            rowCount: filteredRows.length,
            rows: filteredRows,
            TotalVisitas: totalVisitas,
            TotalAtendidas: totalAtendidas,
            TotalNoAtendidas: totalNoAtendidas,
            PorcentajeAtendidas: pctAtendidas,
            PorcentajeNoAtendidas: pctNoAtendidas,
            TiempoEsperaMediana: esperaMediana,
            TiempoEsperaMaximoP90: esperaMaximoP90,
            TiempoEsperaMinimoQ1: esperaMinimoQ1
        };
    }

