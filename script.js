    // Eje Y con pasos de 1, 2 o 5 x 10^n (máximo ~9 marcas: 0, 20k, 40k...)
    function getHistogramScale(maxValue) {
        if (maxValue <= 0) return { max: 10, ticks: [0, 2, 4, 6, 8, 10] };
        const target = maxValue * 1.04;
        let step = 1;
        outer: for (let mag = 1; mag <= 1e9; mag *= 10) {
            for (const m of [1, 2, 5]) {
                if (target / (m * mag) <= 9) { step = m * mag; break outer; }
            }
        }
        const max = Math.ceil(target / step) * step;
        const ticks = [];
        for (let v = 0; v <= max; v += step) ticks.push(v);
        return { max, ticks };
    }

