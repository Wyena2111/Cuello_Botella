    // ================= 6. GRÁFICA APILADA POR CENTRO (FILTRA ÚNICAMENTE POR DescripcionArea) =================
    function getNiceScale(maxValue) {
        if (maxValue <= 0) return { max: 10, step: 2, ticks: [0, 2, 4, 6, 8, 10] };

        const targetTicks = 6;
        const rawStep = maxValue / targetTicks;
        const magnitude = Math.pow(10, Math.floor(Math.log10(rawStep)));
        const residual = rawStep / magnitude;

        let niceMultiplier;
        if (residual <= 1) niceMultiplier = 1;
        else if (residual <= 2) niceMultiplier = 2;
        else if (residual <= 2.5) niceMultiplier = 2.5;
        else if (residual <= 5) niceMultiplier = 5;
        else niceMultiplier = 10;

        const step = niceMultiplier * magnitude;
        const niceMax = Math.ceil(maxValue / step) * step;

        const ticks = [];
        for (let v = 0; v <= niceMax + step * 0.001; v += step) {
            ticks.push(Math.round(v));
        }
        return { max: niceMax, step, ticks };
    }

    function formatAxisTick(val) {
        if (val === 0) return '0';
        if (val >= 1000) {
            const k = val / 1000;
            return Number.isInteger(k) ? `${k}k` : `${k.toFixed(1)}k`;
        }
        return fmtEntero.format(val);
    }

    function aggregateByCentroForArea(selectedArea) {
        const grouped = new Map();

        DATA_RECORDS.forEach(rec => {
            // ÚNICO FILTRO DE LA GRÁFICA: DescripcionArea (ignora por completo Centro)
            if (selectedArea !== 'ALL' && rec.DescripcionArea !== selectedArea) return;

            if (!grouped.has(rec.centro)) {
                grouped.set(rec.centro, {
                    centro: rec.centro,
                    atendidas: 0,
                    noAtendidas: 0,
                    total: 0
                });
            }
            const item = grouped.get(rec.centro);
            item.atendidas += rec.TotalAtendidas;
            item.noAtendidas += rec.TotalNoAtendidas;
            item.total += rec.TotalVisitas;
        });

        return Array.from(grouped.values()).sort((a, b) => b.total - a.total);
    }

